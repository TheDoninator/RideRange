            implementation(libs.androidx.sqlite.bundled)
        }
    }
}

dependencies {
    add("kspAndroid", libs.androidx.room.compiler)
    add("kspIosArm64", libs.androidx.room.compiler)
    add("kspIosSimulatorArm64", libs.androidx.room.compiler)
}

room {
    schemaDirectory("$projectDir/schemas")
}

// Build-time constants for common code (no BuildConfig in Kotlin Multiplatform).
val genAppInfo by tasks.registering {
    val out = layout.buildDirectory.dir("generated/appinfo")
    val version = appVersionName
    inputs.property("version", version)
    outputs.dir(out)
    doLast {
        val f = out.get().file("com/elect/riderange/core/AppVersion.kt").asFile
        f.parentFile.mkdirs()
        f.writeText("package com.elect.riderange.core\n\n/** Generated by shared/build.gradle.kts. */\nconst val APP_VERSION_NAME = \"$version\"\n")
    }
}

// Test fixtures live on disk: the JVM and the iOS simulator can both read the checkout directly.
val genTestPaths by tasks.registering {
    val out = layout.buildDirectory.dir("generated/testpaths")
    val res = file("src/commonTest/resources").absolutePath.replace('\\', '/')
    val assets = rootProject.file("app/src/main/assets").absolutePath.replace('\\', '/')
    val sources = file("src/commonMain/kotlin").absolutePath.replace('\\', '/')
    inputs.property("res", res)
    inputs.property("assets", assets)
    inputs.property("sources", sources)
    outputs.dir(out)
    doLast {
        val f = out.get().file("com/elect/riderange/TestPaths.kt").asFile
        f.parentFile.mkdirs()
        f.writeText("package com.elect.riderange\n\ninternal object TestPaths {\n    const val RESOURCES = \"$res\"\n" +
            "    const val ASSETS = \"$assets\"\n    const val SOURCES = \"$sources\"\n}\n")
    }
}

tasks.matching { it.name.startsWith("compile") || it.name.startsWith("ksp") }.configureEach {
    dependsOn(genAppInfo, genTestPaths)
}

// CI picks a simulator that exists on the runner's Xcode (IOS_SIM_DEVICE, e.g. "iPhone 17").
tasks.withType<org.jetbrains.kotlin.gradle.targets.native.tasks.KotlinNativeSimulatorTest>().configureEach {
    providers.environmentVariable("IOS_SIM_DEVICE").orNull?.let { device.set(it) }
}
